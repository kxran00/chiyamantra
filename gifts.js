function onScroll(){
  const h = innerHeight, y = scrollY, max = Math.max(1, document.documentElement.scrollHeight - h);
  bar.style.width = (y / max * 100) + "%";
  $$(".gcard").forEach((c,i) => {
    const r = c.getBoundingClientRect(); if (r.bottom < -120 || r.top > h + 120) return;
    const t = Math.max(0, Math.min(1, 1 - Math.abs(r.top + r.height/2 - h/2) / (h*.75)));
    const d = i % 2 ? -1 : 1;
    c.style.transform = `perspective(1000px) rotateY(${(1-t)*d*30}deg) rotateX(${(1-t)*10}deg) translateY(${(1-t)*40}px) scale(${(.82+.18*t).toFixed(3)})`;
    c.style.opacity = (.2 + .8*t).toFixed(3);
  });
  $$("[data-par]").forEach(im => {
    const f = im.parentElement, r = f.getBoundingClientRect(); if (r.bottom < 0 || r.top > h) return;
    const m = r.height * 0.09, v = -(r.top + r.height/2 - h/2) * im.dataset.par;
    im.style.transform = `translateY(${Math.max(-m, Math.min(m, v))}px) scale(1.2)`;
  });
  ticking = false;
}
