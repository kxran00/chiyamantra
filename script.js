function onScroll(){
  const y = scrollY, h = innerHeight, max = Math.max(1, document.documentElement.scrollHeight - h);
  bar.style.width = (y / max * 100) + "%";
  if (y < h * 1.2){
    heroBg.style.transform = `translateY(${y*0.35}px) scale(${1 + y/h*0.15})`;
    heroTxt.style.transform = `translateY(${-y*0.5}px)`;
    heroTxt.style.opacity = Math.max(0, 1 - y/(h*0.7));
  }
  if (marqW) marqIn.style.transform = `translateX(${-((y*0.5) % marqW)}px)`;
  $$("[data-par]").forEach(im => {
    const f = im.parentElement, r = f.getBoundingClientRect(); if (r.bottom < 0 || r.top > h) return;
    const m = r.height * 0.09, v = -(r.top + r.height/2 - h/2) * im.dataset.par;
    im.style.transform = `translateY(${Math.max(-m, Math.min(m, v))}px) scale(1.2)`;
  });
  let cur = 0; secs.forEach((s,i) => { if (s.getBoundingClientRect().top < h*0.4) cur = i; });
  links.forEach((a,i) => a.classList.toggle("active", i === cur));
  ticking = false;
}
